-- Futures Academy v2.1
-- Live evaluation result engine.
-- Run after evaluation_engine_v200.sql.

begin;

create table if not exists public.evaluation_trades (
  id bigint generated by default as identity primary key,
  evaluation_id uuid not null references public.evaluation_accounts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  net_profit numeric(14,2) not null,
  balance_after numeric(14,2) not null,
  created_at timestamptz not null default now()
);

create index if not exists evaluation_trades_evaluation_idx
on public.evaluation_trades(evaluation_id, created_at);

alter table public.evaluation_trades enable row level security;

drop policy if exists "Users view own evaluation trades"
on public.evaluation_trades;

create policy "Users view own evaluation trades"
on public.evaluation_trades
for select
to authenticated
using (user_id = auth.uid() or public.is_admin());

grant select on public.evaluation_trades to authenticated;

create or replace function public.apply_evaluation_trade(
  evaluation_id uuid,
  net_profit numeric
)
returns public.evaluation_accounts
language plpgsql
security definer
set search_path = public
as $$
declare
  evaluation public.evaluation_accounts;
  next_balance numeric;
  next_peak numeric;
  next_total_profit numeric;
  next_best_day numeric;
  trailing_floor numeric;
  daily_loss_used numeric;
  consistency_value numeric;
  target_reached boolean;
  consistency_satisfied boolean;
  next_status public.evaluation_status;
  fail_reason text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select * into evaluation
  from public.evaluation_accounts
  where id = evaluation_id
    and user_id = auth.uid()
  for update;

  if not found then
    raise exception 'Evaluation not found';
  end if;

  if evaluation.status <> 'active' then
    raise exception 'Evaluation is not active';
  end if;

  next_balance := evaluation.current_balance + net_profit;
  next_peak := greatest(evaluation.peak_balance, next_balance);
  next_total_profit := evaluation.total_profit + net_profit;
  next_best_day := greatest(evaluation.best_day_profit, net_profit);

  trailing_floor := greatest(
    evaluation.starting_balance - evaluation.max_drawdown,
    next_peak - evaluation.max_drawdown
  );

  daily_loss_used := greatest(
    0,
    evaluation.daily_start_balance - next_balance
  );

  if next_total_profit > 0 and next_best_day > 0 then
    consistency_value := (next_best_day / next_total_profit) * 100;
  else
    consistency_value := 0;
  end if;

  next_status := 'active';
  fail_reason := null;

  if next_balance <= trailing_floor then
    next_status := 'failed';
    fail_reason := 'Trailing drawdown reached';
  elsif daily_loss_used >= evaluation.daily_loss_limit then
    next_status := 'failed';
    fail_reason := 'Daily loss limit reached';
  else
    target_reached :=
      next_balance >= evaluation.starting_balance + evaluation.profit_target;

    consistency_satisfied :=
      consistency_value <= evaluation.consistency_percent
      or next_total_profit <= 0;

    if target_reached and consistency_satisfied then
      next_status := 'passed';
    end if;
  end if;

  update public.evaluation_accounts
  set
    current_balance = next_balance,
    peak_balance = next_peak,
    total_profit = next_total_profit,
    best_day_profit = next_best_day,
    status = next_status,
    failed_reason = fail_reason,
    completed_at = case
      when next_status in ('passed','failed') then now()
      else completed_at
    end,
    updated_at = now()
  where id = evaluation.id
  returning * into evaluation;

  insert into public.evaluation_trades(
    evaluation_id,
    user_id,
    net_profit,
    balance_after
  )
  values (
    evaluation.id,
    auth.uid(),
    net_profit,
    evaluation.current_balance
  );

  return evaluation;
end;
$$;

revoke all on function public.apply_evaluation_trade(uuid, numeric)
from public, anon;

grant execute on function public.apply_evaluation_trade(uuid, numeric)
to authenticated;

commit;
